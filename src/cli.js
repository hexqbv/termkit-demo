#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';

// Subpath imports keep things modular. You can also import everything from 'termkit-ui'.
import {
  input, select, multiselect, number, password, confirm,
} from 'termkit-ui/prompts';
import { spinner, progressBar } from 'termkit-ui/progress';
import { box, divider } from 'termkit-ui/layout';
import { table } from 'termkit-ui/tables';
import { style } from 'termkit-ui/styles';
import { CancelError, NonInteractiveError } from 'termkit-ui';

import {
  FRAMEWORKS, FEATURES, DEFAULTS, validateName, buildPlan, parseArgs,
} from './config.js';

const HELP = `Usage: termkit-demo [options]

Options:
  -y, --yes             Accept all defaults (no prompts, CI friendly)
  --name=<name>         Project name
  --framework=<name>    react | vue | svelte
  -h, --help            Show this help
`;

async function collectAnswers(flags) {
  if (flags.yes) {
    return {
      ...DEFAULTS,
      name: flags.name ?? DEFAULTS.name,
      framework: flags.framework ?? DEFAULTS.framework,
    };
  }

  // Prompts render on stderr, so stdout stays clean for piping.
  const name = flags.name ?? await input({
    message: 'Project name:',
    default: DEFAULTS.name,
    validate: validateName,
  });

  const framework = flags.framework ?? await select({
    message: 'Choose a framework:',
    items: FRAMEWORKS,
    default: DEFAULTS.framework,
  });

  const features = await multiselect({
    message: 'Pick extras (Space to toggle, A for all):',
    items: FEATURES,
  });

  const replicas = await number({
    message: 'Replicas to deploy (1-10):',
    default: DEFAULTS.replicas,
    min: 1,
    max: 10,
  });

  // Secrets are masked and never logged. Only ask when a human is at the keyboard.
  if (process.stdin.isTTY) {
    const token = await password({
      message: 'API token (optional, min 8 chars):',
      mask: '*',
      validate: (v) => v === '' || v.length >= 8 || 'Token must be at least 8 characters',
    });
    if (token) console.error(style.dim(`  (token received: ${token.length} characters, not stored)`));
  }

  const git = await confirm({ message: 'Initialize a git repository?', default: DEFAULTS.git });

  return { name, framework, features, replicas, git };
}

async function scaffold(answers) {
  const plan = buildPlan(answers);
  const target = join(process.cwd(), 'demo-output', answers.name);

  const s = spinner('Creating project folder...').start();
  await sleep(500);
  await mkdir(join(target, 'src'), { recursive: true });
  s.update('Writing files...');
  for (const file of plan) {
    await writeFile(join(target, file.path), `// ${file.path} generated by termkit-demo\n`);
    await sleep(120);
  }
  s.succeed(`Created ${plan.length} files in demo-output/${answers.name}`);

  const bar = progressBar({ total: 20, message: 'Installing dependencies', width: 30 });
  for (let i = 1; i <= 20; i++) {
    bar.update(i);
    await sleep(60);
  }
  bar.complete('Dependencies installed');

  return { plan, target };
}

function printSummary(answers, plan, target) {
  console.log('');
  console.log(divider({ title: 'SUMMARY', width: 60 }));
  console.log(table(
    [
      { setting: 'Name', value: answers.name },
      { setting: 'Framework', value: answers.framework },
      { setting: 'Extras', value: answers.features.join(', ') || 'none' },
      { setting: 'Replicas', value: String(answers.replicas) },
      { setting: 'Git', value: answers.git ? 'yes' : 'no' },
    ],
    {
      columns: [
        { key: 'setting', header: 'SETTING' },
        { key: 'value', header: 'VALUE' },
      ],
      borderStyle: 'rounded',
    },
  ));
  console.log('');
  console.log(table(
    plan.map((f) => ({ file: f.path, bytes: f.size })),
    {
      columns: [
        { key: 'file', header: 'FILE' },
        { key: 'bytes', header: 'BYTES', align: 'right' },
      ],
    },
  ));
  console.log('');
  console.log(box(
    `${style.green('Success!')} Your project is ready.\n\nNext steps:\n  cd ${target}\n  npm install`,
    { title: 'DONE', borderColor: 'green', padding: { left: 2, right: 2 } },
  ));
}

async function main() {
  const flags = parseArgs(process.argv.slice(2));
  if (flags.help) {
    console.log(HELP);
    return;
  }

  console.log(box('Project scaffolder built with termkit-ui', {
    title: 'TERMKIT DEMO', borderStyle: 'double', borderColor: 'cyan', align: 'center',
  }));

  const answers = await collectAnswers(flags);
  const { plan, target } = await scaffold(answers);
  printSummary(answers, plan, target);
}

main().catch((err) => {
  if (err instanceof CancelError) {
    console.error(`\n${style.yellow('Cancelled')} (${err.reason}). Nothing was written.`);
    process.exit(130);
  }
  if (err instanceof NonInteractiveError) {
    console.error(`${style.red('Error:')} ${err.message}\nTip: run with --yes to accept defaults.`);
    process.exit(2);
  }
  console.error(err);
  process.exit(1);
});
